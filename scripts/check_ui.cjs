/* Role-specific DOM + real HTTP workflows. Run against a fresh isolated UI fixture. */
const assert = require('node:assert/strict');
const {browserSession,until,workspace} = require('./ui_test_helpers.cjs');
(async()=>{
  const session=browserSession(), checks=[], pages=[];
  const post=(path,body,role)=>session.request(path,{method:'POST',headers:{'Content-Type':'application/json',...(role?{'X-Workspace-Role':role}:{})},body:JSON.stringify(body)});
  const get=(path,role)=>session.request(path,{headers:{'X-Workspace-Role':role}});
  async function chat(id,customer,message){const response=await post('/chat',{session_id:id,customer_id:customer,token:'demo-'+customer,message});assert.equal(response.status,200);return response.json();}
  try {
    assert((await(await session.request('/agent')).text()).includes('id="login-form"'));
    assert((await(await session.request('/review')).text()).includes('id="login-form"'));
    checks.push('both dashboard entries require sign-in');
    const small=await chat('role-small','C001','499 payment failed');assert.equal(small.status,'resolved');
    const review=await chat('role-large','C001','5000 payment failed');assert.equal(review.status,'awaiting_approval');
    const support=await chat('role-fraud','C002','Someone hacked my account');assert.equal(support.status,'escalated');
    checks.push('customer channel still creates automatic, approval and human cases');
    await session.login('agent');await session.login('approver');
    const agent=await workspace(session,'agent'), approver=await workspace(session,'approver');pages.push(agent,approver);
    assert.deepEqual([...agent.d.querySelectorAll('[data-case]')].map(e=>e.dataset.case),[support.case_id]);
    assert.deepEqual([...approver.d.querySelectorAll('[data-case]')].map(e=>e.dataset.case),[review.case_id]);
    assert.equal(agent.d.querySelector('[data-live-action="approve"]'),null);
    assert.equal(approver.d.querySelector('[data-live-action="message"]'),null);
    checks.push('two tabs show only their own queues and controls');
    assert.equal((await get('/cases/'+review.case_id,'agent')).status,404);
    assert.equal((await get('/cases/'+support.case_id,'approver')).status,404);
    assert.equal((await post('/cases/'+review.case_id+'/approve',{},'agent')).status,403);
    assert.equal((await post('/cases/'+support.case_id+'/message',{message:'Forbidden'},'approver')).status,403);
    checks.push('direct API attempts cannot cross role boundaries');
    agent.d.querySelector('#case-note').value='I will help investigate the payment.';
    agent.d.querySelector('[data-live-action="message"]').click();
    await until(()=>agent.d.querySelector('#case-content').textContent.includes('I will help investigate'),'support reply');
    checks.push('authenticated support reply appears in its case');
    approver.d.querySelector('#case-note').value='Please collect the booking receipt.';
    approver.d.querySelector('[data-live-action="request-info"]').click();
    await until(()=>!approver.d.querySelector('[data-case="'+review.case_id+'"]'),'review handoff');
    agent.d.querySelector('#refresh').click();
    await until(()=>agent.d.querySelector('[data-case="'+review.case_id+'"]'),'support receives handoff');
    agent.d.querySelector('[data-case="'+review.case_id+'"]').click();
    await until(()=>agent.d.querySelector('[data-live-action="return-review"]'),'support information action');
    assert.equal(agent.d.querySelector('[data-live-action="approve"]'),null);
    agent.d.querySelector('#case-note').value='Receipt collected; please review.';
    agent.d.querySelector('[data-live-action="return-review"]').click();
    await until(()=>!agent.d.querySelector('[data-case="'+review.case_id+'"]'),'return review');
    approver.d.querySelector('#refresh').click();
    await until(()=>approver.d.querySelector('[data-live-action="approve"]'),'approval restored');
    checks.push('information handoff moves ownership between queues');
    approver.d.querySelector('[data-live-action="approve"]').click();
    await until(()=>!approver.d.querySelector('[data-case="'+review.case_id+'"]'),'approved case leaves active queue');
    const detail=await(await get('/cases/'+review.case_id,'approver')).json();assert.equal(detail.status,'resolved');
    assert.equal(detail.audit.filter(event=>event.tool==='trigger_reversal'&&event.decision==='executed').length,1);
    assert.equal((await post('/cases/'+review.case_id+'/approve',{},'approver')).status,409);
    checks.push('approval executes once and duplicate approval is blocked');
    const contact=await chat('role-contact','C004','Change my phone');
    approver.d.querySelector('#refresh').click();
    await until(()=>approver.d.querySelector('[data-case="'+contact.case_id+'"]'),'contact queue');
    approver.d.querySelector('[data-case="'+contact.case_id+'"]').click();
    await until(()=>approver.d.querySelector('#case-content').textContent.includes('registered contact change'),'contact details');
    approver.d.querySelector('[data-live-action="approve"]').click();
    await until(()=>!approver.d.querySelector('[data-case="'+contact.case_id+'"]'),'contact approval');
    checks.push('contact approval uses the signed-in approver without OTP');
    const rejected=await chat('role-reject','C010','2500 payment failed');
    approver.d.querySelector('#refresh').click();
    await until(()=>approver.d.querySelector('[data-case="'+rejected.case_id+'"]'),'reject queue');
    approver.d.querySelector('[data-case="'+rejected.case_id+'"]').click();
    await until(()=>approver.d.querySelector('[data-live-action="reject"]'),'reject action');
    approver.d.querySelector('#case-note').value='Evidence is incomplete.';
    approver.d.querySelector('[data-live-action="reject"]').click();
    await until(()=>!approver.d.querySelector('[data-case="'+rejected.case_id+'"]'),'rejected case');
    assert.equal((await(await get('/cases/'+rejected.case_id,'approver')).json()).status,'rejected');
    checks.push('rejection is recorded through the approver interface');
    for(const page of pages){
      const before=page.calls();
      assert(page.w.WorkspaceDemo.runChecks().every(result=>result.passed));
      for(const id of ['02','09','19','20'])page.w.WorkspaceDemo.load(id);
      assert.equal(page.calls(),before,'Judge fixtures must not call the backend');
    }
    checks.push('20 judge checks per role have no live financial side effects');
    const original=agent.w.fetch;agent.w.fetch=async()=>{throw Error('Offline test');};
    agent.d.querySelector('#refresh').click();await until(()=>agent.d.querySelector('#workspace-error').textContent.includes('Offline test'),'offline feedback');
    agent.w.fetch=original;agent.d.querySelector('#refresh').click();await until(()=>agent.d.querySelector('#workspace-error').textContent==='','reconnect');
    checks.push('offline feedback clears on a successful retry');
    await session.request('/agent/logout',{method:'POST'});
    assert.equal((await get('/cases','agent')).status,403);
    assert.equal((await session.request('/review/session')).status,200);
    checks.push('support sign-out preserves the separate approver session');
    for(const page of pages)assert.deepEqual(page.errors,[]);
    console.log(JSON.stringify({passed:checks.length,checks},null,2));
  } finally {for(const page of pages)page.dom.window.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
